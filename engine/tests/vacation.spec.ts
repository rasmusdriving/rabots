import assert from "node:assert/strict";
import { test } from "node:test";
import type { Bot, Schedule } from "../../shared/protocol.js";
import { beginTidy, calm } from "../core/turn-end.js";
import { wake } from "../core/start-helper.js";
import { settle, setup, changeLines } from "./fake.js";

const days: Extract<Schedule, { type: "every" }>["days"] = ["sun", "mon", "tue", "wed", "thu", "fri", "sat"];
const iso = (at: number) => new Date(at).toISOString();

test("vacation stops delivery, survives restart and resumes only future scheduled runs", async (t) => {
  let at = Date.parse("2026-11-19T12:01:00Z");
  const world = (dirs?: ReturnType<typeof setup>["dirs"]) => {
    const w = setup(dirs, () => true, undefined, { clock: () => at, timeZone: "UTC" });
    t.after(() => { if (w.store.isOpen) { w.engine.shutdown(); w.store.close(); } });
    return w;
  };
  const w = world();
  const po = w.engine.createBot("Po");
  const mira = w.engine.createBot({ name: "Mira", purpose: "Reads sample reports" });
  const another = w.engine.createBot({ name: "Robin", mayMessage: [mira.id] });
  const save = (name: string, schedule?: Schedule) => w.engine.saveTrigger({
    botId: mira.id, trigger: { kind: schedule ? "schedule" : "webhook", name, where: "main", prompt: name, enabled: true, ...(schedule ? { schedule } : {}) },
  });
  const every = save("Every five", { type: "every", minutes: 5, days });
  const once = save("Just once", { type: "once", at: "2026-11-19T12:05:00Z" });
  const hook = save("Example hook");
  const secret = w.store.getTrigger(hook.id)!.secret!;
  const channel = w.engine.saveChannel({ channel: { name: "Example channel", allowedSenders: ["tester@example.com"], routes: [{ tag: "Mira", botId: mira.id }] } });
  w.store.addRule(mira.id, "Read");
  assert.throws(() => w.engine.setVacation({ botId: po.id, vacation: true }), /main bot/);
  const away = w.engine.setVacation({ botId: mira.id, vacation: true }).bot;
  assert.equal(away.vacationSince, iso(at));
  assert.equal(away.state, "idle");
  assert.equal(w.engine.hookTarget(hook.id, secret), undefined);
  assert.deepEqual(w.engine.hookCall(hook.id, { has: true, value: {} }), { status: 404 });
  assert.equal(w.engine.channelCall(channel.id, { messageId: "a", from: { name: "Tester", email: "tester@example.com" }, text: "Mira hello", mentions: ["Mira"] }).status, 200);
  assert.equal(w.engine.getChannel(channel.id).lastMessage?.status, "ignored");
  assert.throws(() => w.engine.sendMessage({ botId: mira.id, text: "Do something" }), /Mira is on vacation/);
  assert.throws(() => w.engine.runTrigger(hook.id), /Mira is on vacation/);
  assert.throws(() => w.engine.startFresh(mira.id), /Mira is on vacation/);
  const rt = w.engine.bot(mira.id);
  assert.equal(calm(w.engine, rt), true, "updates can proceed with a bot on vacation");
  assert.equal(beginTidy(w.engine, rt, "test"), false);
  wake(w.engine, rt, { text: "do not wake", purpose: { threadId: rt.threadId, startedBy: "you", hops: 0, fresh: false } });
  assert.equal(rt.wakes.length, 0);
  at += 9 * 60_000;
  w.engine.checkSchedules();
  assert.equal(w.store.lastRun(every.id), undefined);
  assert.equal(w.store.lastRun(once.id), undefined);
  assert.equal(w.sessions.length, 0);
  assert.ok(!w.engine.snapshot().upcoming.some((x) => x.botId === mira.id));
  w.engine.shutdown();
  w.store.close();

  const r = world(w.dirs);
  await settle();
  assert.equal(r.sessions.length, 0);
  const snapshots: Bot[] = r.engine.snapshot().bots;
  assert.deepEqual(snapshots.map((b) => b.id), [po.id, mira.id, another.id]);
  assert.equal(snapshots[1]?.vacationSince, away.vacationSince);
  assert.deepEqual(snapshots[2]?.mayMessage, [mira.id]);
  assert.equal(r.engine.listRules(mira.id).length, 1);
  assert.deepEqual(r.engine.getChannel(channel.id).routes, [{ tag: "Mira", botId: mira.id }]);
  assert.ok(r.engine.listTriggers(mira.id).every((x) => x.resting && x.enabled && !x.nextAt));
  const back = r.engine.setVacation({ botId: mira.id, vacation: false });
  assert.equal(back.bot.vacationSince, undefined);
  assert.equal(back.missedOnce, 1);
  assert.equal(r.store.lastRun(once.id)?.status, "skipped");
  assert.equal(r.store.getTrigger(every.id)?.nextAt, "2026-11-19T12:15:00.000Z");
  assert.equal(r.engine.hookTarget(hook.id, secret), "trigger");
  assert.match(changeLines(r.events, mira.mainThreadId).at(-1)!, /^Back from vacation\. Away since 19 Nov\. 1 schedule's time passed/);
  r.engine.checkSchedules();
  await settle();
  assert.equal(r.sessions.length, 0);
  at += 5 * 60_000;
  r.engine.checkSchedules();
  await settle();
  assert.equal(r.sessions[0]?.sent[0]?.text, "Every five");
});

test("Stop and vacation preserves an open card, a to-do, the chat and held messages through a restart", async (t) => {
  const w = setup();
  const po = w.engine.createBot("Po");
  const mira = w.engine.createBot("Mira");
  t.after(() => { if (w.store.isOpen) { w.engine.shutdown(); w.store.close(); } });
  w.engine.sendMessage({ botId: mira.id, text: "First message" });
  await settle();
  const s = w.sessions[0]!;
  const added = await s.tool("add_todo", { title: "Read the sample", blocks: [{ type: "text", text: "A sample" }], buttons: [{ label: "Done" }] });
  assert.ok(!added.isError);
  const queue = w.engine.sendMessage({ botId: mira.id, text: "Waiting message" });
  const asking = s.tool("ask_human", { question: "Which sample?", choices: ["First", "Second"] });
  await settle();
  const { cards: [card], todos: [todo] } = w.engine.snapshot();
  assert.ok(card?.kind === "question" && todo && queue.queued);
  assert.throws(() => w.engine.setVacation({ botId: mira.id, vacation: true }), /working or has waiting messages/);
  const away = w.engine.setVacation({ botId: mira.id, vacation: true, stop: true }).bot;
  await asking;
  assert.equal(away.state, "idle");
  assert.ok(s.closed);
  assert.deepEqual(w.engine.snapshot().cards, []);
  assert.deepEqual(w.engine.snapshot().todos, []);
  assert.throws(() => w.engine.resolveCard(card.id, { type: "text", text: "Not yet" }), /no longer open/);
  w.engine.sendMessage({ botId: po.id, text: "Try delivery" });
  await settle();
  const main = w.sessions.at(-1)!;
  for (const mode of ["tell", "ask"] as const) {
    const result = await main.tool("message_bot", { to: mira.id, text: "A test", mode });
    assert.equal(result.isError, true);
    assert.equal(result.content[0]?.text, "Mira is on vacation. Only the person or the main bot can bring it back.");
  }
  w.engine.shutdown();
  w.store.close();

  const r = setup(w.dirs);
  t.after(() => { r.engine.shutdown(); r.store.close(); });
  await settle();
  assert.equal(r.sessions.length, 0);
  assert.deepEqual(r.engine.snapshot().cards, []);
  assert.deepEqual(r.engine.snapshot().todos, []);
  assert.equal(r.engine.steerQueued({ botId: mira.id, itemId: queue.id }).steered, false);
  r.engine.setVacation({ botId: mira.id, vacation: false });
  await settle();
  assert.equal(r.sessions.length, 0);
  assert.deepEqual(r.engine.snapshot().cards, [card]);
  assert.deepEqual(r.engine.snapshot().todos, [todo]);
  assert.equal(r.store.getItem(queue.id)?.kind, "user");
  assert.deepEqual(r.engine.bot(mira.id).queue, [queue.id]);
  r.engine.resolveCard(card.id, { type: "text", text: "First" });
  await settle();
  assert.equal(r.sessions[0]?.sent[0]?.text, "Waiting message");
  r.sessions[0]!.reply("Answered");
  await settle();
  assert.equal(r.sessions[0]?.sent.at(-1)?.text, "First");
});

test("only the main bot can change vacation with update_bot and its chat gets both quiet lines", async (t) => {
  const w = setup();
  const po = w.engine.createBot("Po");
  const mira = w.engine.createBot("Mira");
  t.after(() => { w.engine.shutdown(); w.store.close(); });
  w.engine.sendMessage({ botId: po.id, text: "Change vacation" });
  w.engine.sendMessage({ botId: mira.id, text: "Occupy this bot" });
  await settle();
  const p = w.sessions.find((s) => s.settings.botId === po.id)!;
  const m = w.sessions.find((s) => s.settings.botId === mira.id)!;
  assert.match((await p.tool("update_bot", { bot: mira.id, vacation: true })).content[0]!.text, /working.*stop_helper/);
  assert.ok((await p.tool("update_bot", { bot: po.id, vacation: true })).isError);
  assert.ok(!m.toolNames().includes("update_bot"));
  m.reply("Done");
  await settle();
  assert.ok(!(await p.tool("update_bot", { bot: mira.id, vacation: true })).isError);
  assert.match((await p.tool("list_bots", {})).content[0]!.text, /Mira.+on vacation since/);
  assert.match((await p.tool("get_bot", { bot: mira.id, parts: ["settings"] })).content[0]!.text, /Mira.+on vacation since/);
  assert.match((await p.tool("list_triggers", { bot: mira.id })).content[0]!.text, /triggers are resting/);
  p.reply("Sent away");
  await settle();
  w.engine.sendMessage({ botId: po.id, text: "Bring it back" });
  await settle();
  assert.ok(!(await w.sessions.findLast((s) => s.settings.botId === po.id)!.tool("update_bot", { bot: mira.id, vacation: false })).isError);
  w.sessions.findLast((s) => s.settings.botId === po.id)!.reply("Returned");
  await settle();
  assert.ok(changeLines(w.events, po.mainThreadId).some((line) => /Mira: sent on vacation/.test(line)));
  assert.ok(changeLines(w.events, po.mainThreadId).some((line) => /Mira: back from vacation/.test(line)));
});
